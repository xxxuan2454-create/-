# 六亲 (Six Relations) - 基于五行生克
# ═══════════════════════════════════════════════════════════════

def get_liuqin(gua_wuxing: str, yao_dizhi: str) -> str:
    """
    根据卦宫五行和爻的地支五行确定六亲关系
    以卦宫五行为「我」
    - 生我者父母, 我生者子孙
    - 克我者官鬼, 我克者妻财
    - 同我者兄弟
    """
    yao_wx = DI_ZHI.get(yao_dizhi, "")
    if not yao_wx or not gua_wuxing:
        return ""

    if yao_wx == gua_wuxing:
        return "兄弟"
    if WU_XING[yao_wx].sheng == gua_wuxing:
        return "父母"
    if WU_XING[yao_wx].ke == gua_wuxing:
        return "妻财"
    if WU_XING[yao_wx].bei_sheng == gua_wuxing:
        return "子孙"
    if WU_XING[yao_wx].bei_ke == gua_wuxing:
        return "官鬼"
    return ""


def get_liuqin_for_lines(gua_wuxing: str, najia_lines: list[dict]) -> list[str]:
    """获取六爻的六亲关系"""
    return [get_liuqin(gua_wuxing, line["dizhi"]) for line in najia_lines]


