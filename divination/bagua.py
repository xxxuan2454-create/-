def get_najia_for_hexagram(xia_gua_name: str, shang_gua_name: str) -> list[dict]:
    """获取重卦的纳甲信息，返回6爻的干支列表 (从初爻到上爻)"""
    xia = NA_JIA.get(xia_gua_name, {})
    shang = NA_JIA.get(shang_gua_name, {})
    lines = []
    for tg, dz in (xia.get("inner", []) + shang.get("outer", [])):
        lines.append({"tiangan": tg, "dizhi": dz, "wuxing": DI_ZHI.get(dz, "")})
    return lines


