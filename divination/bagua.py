# ═══════════════════════════════════════════════════════════════
# 六爻股票预测分析 (财爻 + 世应 + 六亲生克)
# ═══════════════════════════════════════════════════════════════

def analyze_stock_divination(
    gong_wuxing: str, liuqin: list[str], najia_lines: list[dict],
    shi_yao: int, ying_yao: int, changing_lines: list[int],
    tiyong: dict,
) -> dict:
    """
    综合六爻股票预测分析
    核心: 妻财爻代表股价，妻财旺则涨，妻财弱则跌
    """
    analysis_parts = []
    bullish_signals = 0
    bearish_signals = 0

    # 1. 找到妻财爻位置
    cai_yao_positions = [i + 1 for i, q in enumerate(liuqin) if q == "妻财"]
    zi_sun_positions = [i + 1 for i, q in enumerate(liuqin) if q == "子孙"]
    xiong_di_positions = [i + 1 for i, q in enumerate(liuqin) if q == "兄弟"]
    guan_gui_positions = [i + 1 for i, q in enumerate(liuqin) if q == "官鬼"]
    fu_mu_positions = [i + 1 for i, q in enumerate(liuqin) if q == "父母"]

    # 2. 财爻分析
    if cai_yao_positions:
        for pos in cai_yao_positions:
            idx = pos - 1
            cai_wx = najia_lines[idx]["wuxing"] if idx < len(najia_lines) else ""

            # 旺衰: 得宫位五行生助 = 旺，被克 = 衰
            if cai_wx and gong_wuxing:
                if WU_XING[gong_wuxing].sheng == cai_wx:
                    bullish_signals += 2
                    analysis_parts.append(f"财爻在第{pos}爻({cai_wx})，得宫位{gong_wuxing}所生，财星旺相，主股价有上涨动力")
                elif WU_XING[gong_wuxing].ke == cai_wx:
                    bearish_signals += 2
                    analysis_parts.append(f"财爻在第{pos}爻({cai_wx})，被宫位{gong_wuxing}所克，财星受制，主股价承压")
                elif gong_wuxing == cai_wx:
                    bullish_signals += 1
                    analysis_parts.append(f"财爻在第{pos}爻({cai_wx})，与宫位比和，财星平稳")
                elif cai_wx == WU_XING[gong_wuxing].sheng:
                    bearish_signals += 1
                    analysis_parts.append(f"财爻在第{pos}爻({cai_wx})，生宫位而泄气，财星偏弱")

            # 财爻是否为动爻
            if pos in changing_lines:
                bullish_signals += 1
                analysis_parts.append(f"财爻在第{pos}爻发动，财运有变化之机，若化进神则大涨")

            # 财爻是否持世
            if pos == shi_yao:
                bullish_signals += 2
                analysis_parts.append(f"财爻持世(第{pos}爻)，财来就我，大吉之象，预示得财获利")
    else:
        analysis_parts.append("卦中无财爻，财星不现，需看伏神或变卦中是否有财")
        bearish_signals += 1

    # 3. 世应分析
    shi_liuqin = liuqin[shi_yao - 1] if 0 < shi_yao <= len(liuqin) else ""
    ying_liuqin = liuqin[ying_yao - 1] if 0 < ying_yao <= len(liuqin) else ""
    shi_wx = najia_lines[shi_yao - 1]["wuxing"] if 0 < shi_yao <= len(najia_lines) else ""
    ying_wx = najia_lines[ying_yao - 1]["wuxing"] if 0 < ying_yao <= len(najia_lines) else ""

    analysis_parts.append(f"世爻在第{shi_yao}爻({shi_liuqin})，代表问卦者自身")
    analysis_parts.append(f"应爻在第{ying_yao}爻({ying_liuqin})，代表所问之事(股市)")

    # 世应生克
    if shi_wx and ying_wx:
        if WU_XING[shi_wx].ke == ying_wx:
            bullish_signals += 1
            analysis_parts.append(f"世克应({shi_wx}克{ying_wx})，我制事体，利于主动操作，看涨")
        elif WU_XING[ying_wx].ke == shi_wx:
            bearish_signals += 2
            analysis_parts.append(f"应克世({ying_wx}克{shi_wx})，事体制我，市场不利于己，看跌")
        elif WU_XING[shi_wx].sheng == ying_wx:
            bearish_signals += 1
            analysis_parts.append(f"世生应，泄自身之气，需谨慎")
        elif WU_XING[ying_wx].sheng == shi_wx:
            bullish_signals += 1
            analysis_parts.append(f"应生世，市场有利，收益可期")

    # 4. 子孙爻分析 (生财爻)
    if zi_sun_positions:
        for pos in zi_sun_positions:
            if pos in changing_lines:
                bullish_signals += 1
                analysis_parts.append(f"子孙爻在第{pos}爻发动，子孙生财，财源旺盛，利好上涨")

    # 5. 兄弟爻分析 (克财爻)
    if xiong_di_positions:
        for pos in xiong_di_positions:
            if pos in changing_lines:
                bearish_signals += 2
                analysis_parts.append(f"兄弟爻在第{pos}爻发动，兄弟劫财，主破财下跌，需警惕")

    # 6. 综合判断
    net = bullish_signals - bearish_signals
    if net >= 3:
        overall = "看涨"
        overall_desc = "财爻得力，多方信号明显，股价上涨概率较大"
    elif net >= 1:
        overall = "偏涨"
        overall_desc = "多方略占优势，但需结合体用生克综合判断"
    elif net >= -1:
        overall = "震荡"
        overall_desc = "多空力量均衡，股价可能横盘整理"
    elif net >= -3:
        overall = "偏跌"
        overall_desc = "空方略占优势，需防范下跌风险"
    else:
        overall = "看跌"
        overall_desc = "财爻受制，空方信号明显，股价下跌概率较大"

    # 7. 结合体用
    ti_sentiment = tiyong.get("sentiment", "")
    if ti_sentiment == "bullish":
        if overall in ("偏跌", "看跌"):
            overall_desc += "。但体用生克偏多，需权衡"
    elif ti_sentiment == "bearish":
        if overall in ("偏涨", "看涨"):
            overall_desc += "。但体用生克偏空，需权衡"

    return {
        "cai_yao_positions": cai_yao_positions,
        "zi_sun_positions": zi_sun_positions,
        "xiong_di_positions": xiong_di_positions,
        "shi_liuqin": shi_liuqin,
        "ying_liuqin": ying_liuqin,
        "bullish_signals": bullish_signals,
        "bearish_signals": bearish_signals,
        "net_score": net,
        "overall": overall,
        "overall_desc": overall_desc,
        "analysis": analysis_parts,
    }


def analyze_tiyong(xia_gua: BaGuaData, shang_gua: BaGuaData, changing_lines: list[int]) -> dict:
    """体用生克分析: 体卦(下卦/内卦)为自身, 用卦(上卦/外卦)为事体"""
    ti_wx = xia_gua.wuxing  # 体卦五行
    yong_wx = shang_gua.wuxing  # 用卦五行

    if ti_wx == yong_wx:
        relation = "比和"
        desc = "体用比和，诸事顺遂，股价平稳偏涨"
    elif WU_XING[yong_wx].sheng == ti_wx:
        relation = "用生体"
        desc = "用卦生体卦，大吉之象，有外力相助，股价看涨"
    elif WU_XING[ti_wx].sheng == yong_wx:
        relation = "体生用"
        desc = "体卦生用卦，泄气之象，有消耗之意，股价可能承压"
    elif WU_XING[ti_wx].ke == yong_wx:
        relation = "体克用"
        desc = "体卦克用卦，虽克为吉但需费力，小幅看涨"
    elif WU_XING[yong_wx].ke == ti_wx:
        relation = "用克体"
        desc = "用卦克体卦，大凶之象，外力压制，股价看跌"
    else:
        relation = "未知"
        desc = "需综合判断"

    return {
        "ti_gua": xia_gua.name,
        "ti_wuxing": ti_wx,
        "yong_gua": shang_gua.name,
        "yong_wuxing": yong_wx,
        "relation": relation,
        "description": desc,
        "sentiment": "bullish" if relation in ("用生体", "体克用", "比和") else "bearish",
    }
