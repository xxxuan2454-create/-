@dataclass
class WuXingData:
    name: str
    sheng: str = ""   # 我生 (generates)
    ke: str = ""      # 我克 (controls)
    bei_sheng: str = ""  # 生我 (is generated by)
    bei_ke: str = ""     # 克我 (is controlled by)

    def __post_init__(self):
        _WX_MAP = {
            "金": ("水", "木", "土", "火"),
            "木": ("火", "土", "水", "金"),
            "水": ("木", "火", "金", "土"),
            "火": ("土", "金", "木", "水"),
            "土": ("金", "水", "火", "木"),
        }
        if self.name in _WX_MAP:
            self.sheng, self.ke, self.bei_sheng, self.bei_ke = _WX_MAP[self.name]


WU_XING = {
    name: WuXingData(name)
    for name in ["金", "木", "水", "火", "土"]
}

