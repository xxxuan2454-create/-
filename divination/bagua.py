# ═══════════════════════════════════════════════════════════════
# 爻 (Yao Enum)
# ═══════════════════════════════════════════════════════════════

class Yao(IntEnum):
    LAO_YIN = 0    # 老阴 (0 heads, 3 tails) → 变爻 (阴→阳)
    SHAO_YANG = 1  # 少阳 (1 head, 2 tails)  → 静爻 (阳)
    SHAO_YIN = 2   # 少阴 (2 heads, 1 tail)  → 静爻 (阴)
    LAO_YANG = 3   # 老阳 (3 heads, 0 tails) → 变爻 (阳→阴)

    @property
    def is_changing(self) -> bool:
        return self in (Yao.LAO_YIN, Yao.LAO_YANG)

    @property
    def yin_yang(self) -> str:
        """返回本卦中的阴阳"""
        return "阳" if self in (Yao.SHAO_YANG, Yao.LAO_YANG) else "阴"

    @property
    def line_code(self) -> str:
        """1=阳, 2=阴 用于构建卦码"""
        return "1" if self in (Yao.SHAO_YANG, Yao.LAO_YANG) else "2"

    @property
    def changing_line_code(self) -> str:
        """变卦中该爻的阴阳"""
        return "2" if self in (Yao.SHAO_YANG, Yao.LAO_YANG) else "1"

    @property
    def display(self) -> str:
        return {Yao.LAO_YIN: "老阴 ⚋⚋", Yao.SHAO_YANG: "少阳 ⚊",
                Yao.SHAO_YIN: "少阴 ⚋", Yao.LAO_YANG: "老阳 ⚊⚊"}[self]


